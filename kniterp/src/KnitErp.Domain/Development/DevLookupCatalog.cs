    public static bool HasCodes(DevLookupKind kind) => kind != DevLookupKind.MachineClass;

    public static IReadOnlyList<(int? Code, string Name)> Values(DevLookupKind kind) => kind switch
    {
        DevLookupKind.Category => Categories,
        DevLookupKind.PatternKind => PatternKinds,
        DevLookupKind.Weave => Numbered(Weaves),
        DevLookupKind.MachineClass => MachineClasses.Select(n => ((int?)null, n)).ToList(),
        DevLookupKind.ReworkReason => Numbered(ReworkReasons),
        DevLookupKind.MeasurePoint => Numbered(MeasurePoints),
        DevLookupKind.MachineBrand => Brands.Select(b => ((int?)b.Code, b.Name)).ToList(),
        DevLookupKind.MachineType => Numbered(MachineTypes),
        DevLookupKind.DetailName => Numbered(Details),
        DevLookupKind.YarnKind => Numbered(Yarns),
        DevLookupKind.Composition => Numbered(Compositions),
        DevLookupKind.Finishing => Numbered(Finishings),
        DevLookupKind.SizeScale => Numbered(SizeScales),
        _ => [],
    };

