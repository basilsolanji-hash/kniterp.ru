    public static IReadOnlyList<string> Models(int? brandCode) =>
        brandCode is { } code && Brands.FirstOrDefault(b => b.Code == code) is { Models: { } models } ? models : [];

    private static List<(int? Code, string Name)> Numbered(IEnumerable<string> names) => names.Select((n, i) => ((int?)(i + 1), n)).ToList();

